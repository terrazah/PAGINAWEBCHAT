CREATE OR REPLACE FUNCTION public.obtener_salas_chat(p_session_token text)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  viewer_id uuid;
  rooms jsonb;
BEGIN
  viewer_id := public.media_session_profile(p_session_token);
  IF viewer_id IS NULL THEN
    RETURN jsonb_build_object('ok', false, 'code', 'INVALID_SESSION');
  END IF;

  SELECT coalesce(jsonb_agg(
    jsonb_build_object(
      'id', sala.id,
      'nombre', sala.nombre,
      'slug', sala.slug,
      'usuarios_activos', (
        SELECT count(DISTINCT mensaje.autor_id)
        FROM public.mensajes_salas AS mensaje
        WHERE mensaje.sala_id = sala.id
          AND mensaje.creado_en >= now() - interval '10 minutes'
      ),
      'es_favorita', EXISTS (
        SELECT 1
        FROM public.favoritos_salas AS favorito
        WHERE favorito.sala_id = sala.id
          AND favorito.usuario_id = viewer_id
      )
    )
    ORDER BY sala.nombre
  ), '[]'::jsonb)
  INTO rooms
  FROM public.salas_chat AS sala
  WHERE sala.activa = true;

  RETURN jsonb_build_object('ok', true, 'rooms', rooms);
END;
$$;

CREATE OR REPLACE FUNCTION public.obtener_sala_chat(
  p_session_token text,
  p_sala_id bigint
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  viewer_id uuid;
  room_data jsonb;
  messages_data jsonb;
BEGIN
  viewer_id := public.media_session_profile(p_session_token);
  IF viewer_id IS NULL THEN
    RETURN jsonb_build_object('ok', false, 'code', 'INVALID_SESSION');
  END IF;

  SELECT jsonb_build_object(
    'id', sala.id,
    'nombre', sala.nombre,
    'slug', sala.slug,
    'usuarios_activos', (
      SELECT count(DISTINCT mensaje.autor_id)
      FROM public.mensajes_salas AS mensaje
      WHERE mensaje.sala_id = sala.id
        AND mensaje.creado_en >= now() - interval '10 minutes'
    ),
    'es_favorita', EXISTS (
      SELECT 1
      FROM public.favoritos_salas AS favorito
      WHERE favorito.sala_id = sala.id
        AND favorito.usuario_id = viewer_id
    )
  )
  INTO room_data
  FROM public.salas_chat AS sala
  WHERE sala.id = p_sala_id
    AND sala.activa = true;

  IF room_data IS NULL THEN
    RETURN jsonb_build_object('ok', false, 'code', 'ROOM_NOT_FOUND');
  END IF;

  SELECT coalesce(jsonb_agg(
    jsonb_build_object(
      'id', mensaje.id,
      'autor_id', perfil.id,
      'autor_alias', perfil.username,
      'avatar_url', perfil.avatar_url,
      'es_vip', coalesce(perfil.is_vip, perfil.es_vip, false),
      'contenido', mensaje.contenido,
      'creado_en', mensaje.creado_en
    )
    ORDER BY mensaje.creado_en DESC, mensaje.id DESC
  ), '[]'::jsonb)
  INTO messages_data
  FROM (
    SELECT *
    FROM public.mensajes_salas
    WHERE sala_id = p_sala_id
    ORDER BY creado_en DESC, id DESC
    LIMIT 12
  ) AS mensaje
  JOIN public.perfiles_dk AS perfil ON perfil.id = mensaje.autor_id;

  RETURN jsonb_build_object(
    'ok', true,
    'room', room_data,
    'messages', messages_data
  );
END;
$$;

CREATE OR REPLACE FUNCTION public.enviar_mensaje_sala_seguro(
  p_session_token text,
  p_sala_id bigint,
  p_contenido text
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  sender_id uuid;
  clean_content text;
  last_sent_at timestamptz;
  inserted_message public.mensajes_salas;
BEGIN
  sender_id := public.media_session_profile(p_session_token);
  IF sender_id IS NULL THEN
    RETURN jsonb_build_object('ok', false, 'code', 'INVALID_SESSION');
  END IF;

  IF NOT EXISTS (
    SELECT 1
    FROM public.salas_chat
    WHERE id = p_sala_id
      AND activa = true
  ) THEN
    RETURN jsonb_build_object('ok', false, 'code', 'ROOM_NOT_FOUND');
  END IF;

  clean_content := nullif(btrim(coalesce(p_contenido, '')), '');
  IF clean_content IS NULL THEN
    RETURN jsonb_build_object('ok', false, 'code', 'EMPTY_MESSAGE');
  END IF;
  IF char_length(clean_content) > 250 THEN
    RETURN jsonb_build_object('ok', false, 'code', 'MESSAGE_TOO_LONG');
  END IF;

  -- El bloqueo evita dos envíos simultáneos del mismo usuario. El control
  -- vive separado del historial porque los mensajes viejos se eliminan.
  PERFORM pg_advisory_xact_lock(hashtext('konekto:sala-spam:' || sender_id::text));
  SELECT ultimo_envio_en
  INTO last_sent_at
  FROM public.control_mensajes_salas
  WHERE usuario_id = sender_id
  FOR UPDATE;

  IF last_sent_at IS NOT NULL
     AND last_sent_at >= now() - interval '5 seconds' THEN
    RETURN jsonb_build_object('ok', false, 'code', 'TOO_FAST');
  END IF;

  INSERT INTO public.mensajes_salas (sala_id, autor_id, contenido)
  VALUES (p_sala_id, sender_id, clean_content)
  RETURNING * INTO inserted_message;

  INSERT INTO public.control_mensajes_salas (usuario_id, ultimo_envio_en)
  VALUES (sender_id, inserted_message.creado_en)
  ON CONFLICT (usuario_id) DO UPDATE
  SET ultimo_envio_en = EXCLUDED.ultimo_envio_en;

  RETURN jsonb_build_object(
    'ok', true,
    'message', jsonb_build_object(
      'id', inserted_message.id,
      'creado_en', inserted_message.creado_en
    )
  );
END;
$$;

CREATE OR REPLACE FUNCTION public.alternar_favorito_sala(
  p_session_token text,
  p_sala_id bigint
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  viewer_id uuid;
  is_favorite boolean;
BEGIN
  viewer_id := public.media_session_profile(p_session_token);
  IF viewer_id IS NULL THEN
    RETURN jsonb_build_object('ok', false, 'code', 'INVALID_SESSION');
  END IF;

  IF NOT EXISTS (
    SELECT 1
    FROM public.salas_chat
    WHERE id = p_sala_id
      AND activa = true
  ) THEN
    RETURN jsonb_build_object('ok', false, 'code', 'ROOM_NOT_FOUND');
  END IF;

  IF EXISTS (
    SELECT 1
    FROM public.favoritos_salas
    WHERE usuario_id = viewer_id
      AND sala_id = p_sala_id
  ) THEN
    DELETE FROM public.favoritos_salas
    WHERE usuario_id = viewer_id
      AND sala_id = p_sala_id;
    is_favorite := false;
  ELSE
    INSERT INTO public.favoritos_salas (usuario_id, sala_id)
    VALUES (viewer_id, p_sala_id)
    ON CONFLICT DO NOTHING;
    is_favorite := true;
  END IF;

  RETURN jsonb_build_object('ok', true, 'es_favorita', is_favorite);
END;
$$;

