-- Chat Konekto — Fase 5: salas de chat públicas.
-- Ejecutar después de las migraciones base de perfiles y sesiones.

CREATE TABLE IF NOT EXISTS public.salas_chat (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre text NOT NULL UNIQUE,
  slug text NOT NULL UNIQUE,
  activa boolean NOT NULL DEFAULT true,
  creado_en timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.mensajes_salas (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sala_id bigint NOT NULL REFERENCES public.salas_chat(id) ON DELETE CASCADE,
  autor_id uuid NOT NULL REFERENCES public.perfiles_dk(id) ON DELETE CASCADE,
  contenido text NOT NULL CHECK (char_length(btrim(contenido)) BETWEEN 1 AND 250),
  creado_en timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.favoritos_salas (
  usuario_id uuid NOT NULL REFERENCES public.perfiles_dk(id) ON DELETE CASCADE,
  sala_id bigint NOT NULL REFERENCES public.salas_chat(id) ON DELETE CASCADE,
  creado_en timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (usuario_id, sala_id)
);

CREATE TABLE IF NOT EXISTS public.control_mensajes_salas (
  usuario_id uuid PRIMARY KEY REFERENCES public.perfiles_dk(id) ON DELETE CASCADE,
  ultimo_envio_en timestamptz NOT NULL
);

-- CREATE TABLE IF NOT EXISTS no modifica tablas que ya existían. Estas
-- columnas hacen la migración compatible con un intento anterior que haya
-- creado las tablas sin creado_en (o con otro nombre de fecha).
ALTER TABLE public.salas_chat
