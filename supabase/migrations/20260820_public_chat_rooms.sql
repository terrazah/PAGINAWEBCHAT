CREATE OR REPLACE FUNCTION public.limitar_mensajes_sala()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  -- Serializa inserciones simultáneas en la misma sala para que el límite
  -- sea estricto incluso cuando llegan dos comentarios a la vez.
  PERFORM pg_advisory_xact_lock(hashtext('konekto:sala:' || NEW.sala_id::text));

  DELETE FROM public.mensajes_salas AS mensaje
  WHERE mensaje.id IN (
    SELECT id
    FROM public.mensajes_salas
    WHERE sala_id = NEW.sala_id
    ORDER BY creado_en DESC, id DESC
    OFFSET 12
  );

  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS mensajes_salas_max_12
  ON public.mensajes_salas;

CREATE TRIGGER mensajes_salas_max_12
AFTER INSERT ON public.mensajes_salas
FOR EACH ROW
EXECUTE FUNCTION public.limitar_mensajes_sala();

-- Limpieza inicial por si la tabla ya tenía datos antes de instalar el trigger.
WITH ordenados AS (
  SELECT
    id,
    row_number() OVER (
      PARTITION BY sala_id
      ORDER BY creado_en DESC, id DESC
    ) AS posicion
  FROM public.mensajes_salas
)
DELETE FROM public.mensajes_salas AS mensaje
USING ordenados
WHERE mensaje.id = ordenados.id
  AND ordenados.posicion > 12;

